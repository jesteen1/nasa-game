export const PART_MAP: Record<string, Part> = Object.fromEntries(
  PARTS.map((p) => [p.id, p]),
);

export function getPart(id: string): Part {
  const p = PART_MAP[id];
  if (!p) throw new Error(`Unknown part: ${id}`);
  return p;
}

export function partsForSlot(category: Part["category"], tier: number): Part[] {
  return PARTS.filter((p) => p.category === category && p.tiers.includes(tier));
}

